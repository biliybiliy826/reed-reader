def demo_book() -> Book:
    titles = ["第一章 窗边的光", "第二章 雨后的河岸", "第三章 旧书店", "第四章 慢一点", "第五章 灯火与归途"]
    return Book("把片刻留给自己", "苇读 · 原创示例", [
        Chapter(title, title + "\n\n" + "\n\n".join(PARAGRAPHS[i:] + PARAGRAPHS[:i]))
        for i, title in enumerate(titles)
    ], "DEMO")
